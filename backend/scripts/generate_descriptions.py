def format_title_reference(name: str) -> str:
    """Format name properly inside a sentence without broken quotes."""
    clean = name.strip()
    # If it already has quotes like «...», don't wrap in more quotes
    if "«" in clean:
        return clean
    return f"«{clean}»"


